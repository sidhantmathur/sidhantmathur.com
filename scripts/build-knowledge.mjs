// Builds two artifacts from content/knowledge/*.md, both git-ignored:
//
//   1. KNOWLEDGE_BASE — the files concatenated in fixed order, injected into the
//      system prompt. Byte-identical across builds so the Anthropic prompt cache
//      stays stable.
//   2. CITATIONS — a structured index of resume.md's sections, used by the
//      context panel.
//
// (2) exists so the panel and the model read the SAME source. The panel used to
// hold a hand-maintained copy of these sections, which meant the evidence shown
// beside an answer could silently drift from the evidence the answer was built
// from. Editing content/knowledge/resume.md now updates both.
//
// Run as `predev` and `prebuild`.

import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

// Fixed order — do not reorder without re-checking the token budget (~8k target).
const FILES = [
  "resume.md",
  "bio.md",
  "projects-adarle20.md",
  "projects-nokia.md",
  "projects-dell.md",
  "faq.md",
];

const parts = FILES.map((name) =>
  readFileSync(join(root, "content", "knowledge", name), "utf8").trim(),
);

// Join with blank-line separators between files.
const knowledge = parts.join("\n\n");

// JSON.stringify escapes backticks, ${, backslashes, and newlines safely —
// avoids the fragility of hand-escaping a template literal.
const out = `// AUTO-GENERATED by scripts/build-knowledge.mjs — do not edit by hand.
export const KNOWLEDGE_BASE = ${JSON.stringify(knowledge)};
`;

// --- Citation index ------------------------------------------------------
//
// Parses resume.md's `##` sections and, inside Experience, its `###` employer
// blocks. Each becomes a citable unit with a stable slug the chat tools and the
// panel both address.

const resume = readFileSync(join(root, "content", "knowledge", "resume.md"), "utf8");

function slugify(text) {
  return text
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}

// Bullets are `- ` lines; wrapped continuation lines are indented. Rejoin them
// so a bullet is one string rather than one string per source line.
function parseBullets(body) {
  const out = [];
  for (const line of body.split("\n")) {
    if (/^\s*-\s+/.test(line)) {
      out.push(line.replace(/^\s*-\s+/, "").trim());
    } else if (out.length && line.trim() && /^\s+/.test(line)) {
      out[out.length - 1] += " " + line.trim();
    } else if (!line.trim()) {
      // blank line ends the current bullet run
    }
  }
  return out;
}

const citations = [];

// Split on `## ` headings, keeping the heading text.
const sections = resume.split(/\n## /).slice(1);
for (const section of sections) {
  const nl = section.indexOf("\n");
  const heading = section.slice(0, nl).trim();
  const body = section.slice(nl + 1);

  if (heading.toLowerCase() === "experience") {
    // Each `### Employer` is its own citable unit.
    for (const block of body.split(/\n### /).slice(1)) {
      const bnl = block.indexOf("\n");
      const employer = block.slice(0, bnl).trim();
      const bbody = block.slice(bnl + 1);
      // The first `**bold**` line is the role/dateline.
      const roleMatch = bbody.match(/\*\*(.+?)\*\*/);
      // Strip parentheticals and everything after the first em dash so the id
      // stays short and stable: `A Darle 20 ("Let's Go 20") — adarle20.com —
      // Toronto, ON` becomes `a-darle-20`.
      citations.push({
        id: slugify(employer.split("—")[0].replace(/\(.*?\)/g, "")),
        section: "Experience",
        heading: employer,
        meta: roleMatch ? roleMatch[1].trim() : "",
        bullets: parseBullets(bbody),
      });
    }
    continue;
  }

  const bullets = parseBullets(body);
  const prose = body
    .split("\n\n")
    .map((p) => p.replace(/\n/g, " ").trim())
    .filter((p) => p && !p.startsWith("-") && !p.startsWith("#"));

  citations.push({
    id: slugify(heading),
    section: heading,
    heading,
    meta: "",
    bullets: bullets.length ? bullets : prose,
  });
}

const outCitations = `// AUTO-GENERATED by scripts/build-knowledge.mjs — do not edit by hand.
// Structured index of content/knowledge/resume.md. The context panel renders
// these, so what a visitor sees as evidence is the same text the model reads.
export type Citation = {
  id: string;
  section: string;
  heading: string;
  meta: string;
  bullets: string[];
};

export const CITATIONS: Citation[] = ${JSON.stringify(citations, null, 2)};

export const CITATION_BY_ID: Record<string, Citation> = Object.fromEntries(
  CITATIONS.map((c) => [c.id, c]),
);
`;

const target = join(root, "lib", "knowledge.generated.ts");
mkdirSync(dirname(target), { recursive: true });
writeFileSync(target, out, "utf8");

const citationTarget = join(root, "lib", "citations.generated.ts");
writeFileSync(citationTarget, outCitations, "utf8");

console.log(
  `[build-knowledge] wrote ${target} (${knowledge.length} chars from ${FILES.length} files)`,
);
console.log(
  `[build-knowledge] wrote ${citationTarget} (${citations.length} citable sections: ${citations
    .map((c) => c.id)
    .join(", ")})`,
);
